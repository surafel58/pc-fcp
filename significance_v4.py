"""Significance of the PC-FCP vs baseline differences across seeds (examiner comment B5).

Unit of replication = one training seed (its own long-tailed draw, client partition, model and
calibration split). The noise draws inside a seed are NOT independent replicates of the whole
experiment; they are averaged first, so every test below has one value per seed.

Per dataset, metric and budget eps:
  d_s = metric(PC-FCP, seed s) - metric(comparator, seed s)      (mean over the noise draws)
  report mean d, 95% t-interval, paired t-test p, exact Wilcoxon signed-rank p, sign count,
  Holm-adjusted p over the five budgets.
Trend over eps: per seed, OLS slope of d_s on log2(eps); one-sample t-test of the slopes.
Variance split: between-seed std of the seed means vs mean within-seed std over the noise draws.

Usage:
  python significance_v4.py --eval results/v4/eval_r100 [--eval results/v4_seeds/eval_r100 ...]
                            --out results/v4/SIGNIFICANCE_3seed.md
"""
import argparse
import glob
import os

import numpy as np
import pandas as pd
from scipy import stats

COMPARATORS = {
    'fedcp2qq_marg': 'FedCP2-QQ',
    'fedcp2qq_pc_pfallback': 'FedCP2-QQ, per class (private fallback)',
}
METRICS = {'worst_cov': ('Worst-class coverage (pp)', 100.0),
           'set_size': ('Mean set size (labels)', 1.0),
           'marginal_bal': ('Macro coverage on the balanced test set (pp)', 100.0)}
DATASETS = {'cifar10': 'CIFAR-10-LT', 'cifar100': 'CIFAR-100-LT', 'text': '20 Newsgroups'}
EPS = [1.0, 2.0, 3.0, 4.0, 8.0]


def load(dirs):
    cols = ['tag', 'seed', 'method', 'eps', 'draw'] + list(METRICS)
    fs = [f for d in dirs for f in glob.glob(os.path.join(d, '*_K10_dir0.5_*__*.csv'))]
    fs = [f for f in fs if '_cal' not in os.path.basename(f) and '_if100' not in os.path.basename(f)]
    d = pd.concat([pd.read_csv(f, usecols=cols) for f in fs], ignore_index=True)
    d['ds'] = d.tag.str.split('_').str[0]
    d = d[d.method.isin(['pcfcp', *COMPARATORS]) & d.eps.isin(EPS)]
    return d.drop_duplicates(['tag', 'method', 'eps', 'draw'], keep='last')


def holm(p):
    p = np.asarray(p, float)
    order = np.argsort(p)
    adj = np.empty_like(p)
    run = 0.0
    for i, j in enumerate(order):
        run = max(run, (len(p) - i) * p[j])
        adj[j] = min(1.0, run)
    return adj


def wilcoxon_p(x):
    x = np.asarray(x, float)
    if np.allclose(x, 0):
        return 1.0
    try:
        return stats.wilcoxon(x, method='exact').pvalue
    except ValueError:
        return float('nan')


def fmt_p(p):
    if not np.isfinite(p):
        return 'n/a'
    return '<0.001' if p < 0.001 else f'{p:.3f}'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--eval', action='append', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--model-div', type=int, default=1,
                    help='replicate unit = seed // model-div (100 for the resplit runs, whose tag seed '
                         'is 100 * model seed + repeat; the repeats and noise draws are averaged first)')
    a = ap.parse_args()

    d = load(a.eval)
    if a.model_div > 1:
        d['seed'] = d['seed'] // a.model_div
    seed_means = d.groupby(['ds', 'seed', 'method', 'eps'])[list(METRICS)].mean()
    within_sd = d.groupby(['ds', 'seed', 'method', 'eps'])[list(METRICS)].std(ddof=1)

    L = ['# Significance of PC-FCP vs the baselines across seeds', '',
         'Generated by `significance_v4.py` from: ' + ', '.join(f'`{e}`' for e in a.eval), '',
         'One value per seed (mean over its noise draws). Difference = PC-FCP minus comparator; '
         'for coverage a positive difference favours PC-FCP, for set size a negative one does. '
         'p values: paired t-test, exact Wilcoxon signed-rank, Holm adjustment over the five budgets '
         '(applied to the t-test p). With n seeds the smallest possible two-sided Wilcoxon p is '
         '2 / 2^n (0.25 for n = 3, 0.002 for n = 10).', '']

    rows_csv = []
    for ds, ds_name in DATASETS.items():
        if ds not in seed_means.index.get_level_values('ds'):
            continue
        seeds = sorted(seed_means.loc[ds].index.get_level_values('seed').unique())
        n = len(seeds)
        L += [f'## {ds_name} ({n} seeds: {", ".join(map(str, seeds))})', '']
        for comp, comp_name in COMPARATORS.items():
            for m, (m_name, scale) in METRICS.items():
                L += [f'### {m_name}: PC-FCP vs {comp_name}', '',
                      '| eps | PC-FCP | comparator | mean diff | 95% CI | t p | Holm p | Wilcoxon p | PC-FCP ahead |',
                      '|---|---|---|---|---|---|---|---|---|']
                diffs, recs = {}, []
                for e in EPS:
                    try:
                        x = seed_means.loc[(ds, slice(None), 'pcfcp', e), m].droplevel([0, 2, 3])
                        y = seed_means.loc[(ds, slice(None), comp, e), m].droplevel([0, 2, 3])
                    except KeyError:
                        continue
                    common = x.index.intersection(y.index)
                    dd = (x[common] - y[common]).values * scale
                    diffs[e] = pd.Series(dd, index=common)
                    mu = dd.mean()
                    if n > 1 and dd.std(ddof=1) > 0:
                        se = dd.std(ddof=1) / np.sqrt(len(dd))
                        h = stats.t.ppf(0.975, len(dd) - 1) * se
                        tp = stats.ttest_1samp(dd, 0.0).pvalue
                    else:
                        h, tp = float('nan'), float('nan')
                    better = (dd > 0) if m != 'set_size' else (dd < 0)
                    recs.append(dict(eps=e, pc=x[common].mean() * scale, cp=y[common].mean() * scale,
                                     mu=mu, h=h, tp=tp, wp=wilcoxon_p(dd), k=int(better.sum()), n=len(dd)))
                if not recs:
                    continue
                adj = holm([r['tp'] if np.isfinite(r['tp']) else 1.0 for r in recs])
                for r, hp in zip(recs, adj):
                    L.append(f"| {r['eps']:g} | {r['pc']:.2f} | {r['cp']:.2f} | {r['mu']:+.2f} | "
                             f"[{r['mu'] - r['h']:+.2f}, {r['mu'] + r['h']:+.2f}] | {fmt_p(r['tp'])} | "
                             f"{fmt_p(hp)} | {fmt_p(r['wp'])} | {r['k']}/{r['n']} |")
                    rows_csv.append(dict(dataset=ds, comparator=comp, metric=m, n_seeds=r['n'], eps=r['eps'],
                                         pcfcp=r['pc'], comp=r['cp'], diff=r['mu'], ci_half=r['h'],
                                         t_p=r['tp'], holm_p=hp, wilcoxon_p=r['wp'], n_ahead=r['k']))
                # trend over eps: slope of the per-seed difference on log2(eps)
                D = pd.DataFrame(diffs).dropna()
                if D.shape[0] >= 2 and D.shape[1] >= 3:
                    lx = np.log2(np.array(D.columns, float))
                    slopes = np.array([np.polyfit(lx, row.values, 1)[0] for _, row in D.iterrows()])
                    sp = stats.ttest_1samp(slopes, 0.0).pvalue if slopes.std(ddof=1) > 0 else float('nan')
                    L += ['', f'Trend over eps: slope of the difference per doubling of eps = '
                              f'{slopes.mean():+.2f} (per seed: {", ".join(f"{s:+.2f}" for s in slopes)}), '
                              f't-test p = {fmt_p(sp)}.']
                L.append('')
        # variance split for PC-FCP and the comparators
        within = 'noise and re-split' if a.model_div > 1 else 'noise only'
        L += [f'### Variance split, worst-class coverage (pp)', '',
              f'| method | eps | between-seed std | mean within-seed std ({within}) |', '|---|---|---|---|']
        for meth in ['pcfcp', *COMPARATORS]:
            for e in EPS:
                try:
                    sm = seed_means.loc[(ds, slice(None), meth, e), 'worst_cov'] * 100
                    ws = within_sd.loc[(ds, slice(None), meth, e), 'worst_cov'] * 100
                except KeyError:
                    continue
                L.append(f'| {meth} | {e:g} | {sm.std(ddof=1):.2f} | {ws.mean():.2f} |')
        L.append('')

    with open(a.out, 'w', encoding='utf-8') as f:
        f.write('\n'.join(L) + '\n')
    pd.DataFrame(rows_csv).to_csv(os.path.splitext(a.out)[0] + '.csv', index=False)
    print('wrote', a.out)


if __name__ == '__main__':
    main()
